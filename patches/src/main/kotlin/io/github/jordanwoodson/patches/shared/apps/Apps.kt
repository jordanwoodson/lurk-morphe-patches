// The apps as the shared patches see them (see LurkApp). Each app's own patches stay in its folder.

internal val TWITCH = LurkApp(
    slug = "twitch",
    compatibility = COMPATIBILITY_TWITCH,
    // Records each match as a locator (twitch.match.<fingerprint>), as every Twitch patch does.
    matcher = { fingerprint, what -> fingerprint.twitchMatch(what) },
    applicationClass = "Ltv/twitch/android/app/consumer/TwitchApplication;",
    // Twitch's content providers start before Application.onCreate and may have started the settings already.
    settingsInit = "Lio/github/jordanwoodson/extension/shared/twitch/TwitchPrivacy;->initSettingsOnce(Landroid/content/Context;)V",
    reactNative = ReactNative(TWITCH_BUNDLE, TwitchBundleLoaderFingerprint),
    // Twitch requires Android 12L, so every supported device understands adaptive vector icons.
    icon = RecoloredFigure("#9146FF"),
    // Android refuses a second install whose provider authority is already used by the original app.
    cloneRules = listOf(AmazonSignIn),
    trackingPermissions = setOf(
        "com.google.android.gms.permission.AD_ID",
        "com.google.android.finsky.permission.BIND_GET_INSTALL_REFERRER_SERVICE",
    ),
)

