internal val RUMBLE = LurkApp(
    slug = "rumble",
    compatibility = COMPATIBILITY_RUMBLE,
    matcher = { fingerprint, what -> fingerprint.single(what) },
    applicationClass = "Lcom/rumble/battles/RumbleApplication;",
    // Generated by `bin/app-icon rumble <artwork>`. Each file replaces the one Rumble ships under the same
    // name, so resource IDs and the manifest's @mipmap/ic_launcher references stay untouched.
    icon = LauncherArtwork(
        "rumble/icon",
        listOf(
            "drawable/ic_launcher_background.xml",
            "drawable/ic_launcher_foreground.xml",
            "mipmap-anydpi/ic_launcher.xml",
            "mipmap-anydpi/ic_launcher_round.xml",
        ) + listOf("mdpi", "hdpi", "xhdpi", "xxhdpi", "xxxhdpi").flatMap { dpi ->
            listOf("mipmap-$dpi/ic_launcher.webp", "mipmap-$dpi/ic_launcher_round.webp")
        },
    ),
    // Rumble also declares names outside its package: a content provider its other apps read, and the
    // permission guarding it. A second install with the same names would be refused, so they move too.
    // Rumble's code uses the provider's authority as a constant, so it changes there as well.
    cloneRules = listOf(
        OutsideName("com.rumble.provider", "provider", inCode = true),
        OutsideName("com.rumble.READ_RUMBLE_DATA", "READ_RUMBLE_DATA"),
    ),
    // Permissions only trackers use. Without AD_ID, Google Play services hands every SDK, and Rumble's own
    // requests (ad_device_id, watch progress), the all-zero advertising ID on Android 13 and newer (API 33,
    // where the permission was introduced); older Android versions don't check it. The rest feed install
    // attribution and ad measurement. READ_PHONE_STATE is declared but never requested or used.
    trackingPermissions = setOf(
        "com.google.android.gms.permission.AD_ID",
        "android.permission.ACCESS_ADSERVICES_AD_ID",
        "android.permission.ACCESS_ADSERVICES_ATTRIBUTION",
        "android.permission.AD_SERVICES_CONFIG",
        "com.google.android.finsky.permission.BIND_GET_INSTALL_REFERRER_SERVICE",
        "com.samsung.android.mapsagent.permission.READ_APP_INFO",
        "com.huawei.appmarket.service.commondata.permission.GET_COMMON_DATA",
        "android.permission.READ_PHONE_STATE",
    ),
    // Package visibility AppsFlyer uses to read install referrers from other stores.
    trackingQueries = TrackingQueries(
        packages = setOf("com.samsung.android.mapsagent"),
        actions = setOf("com.appsflyer.referrer.INSTALL_PROVIDER"),
    ),
)
